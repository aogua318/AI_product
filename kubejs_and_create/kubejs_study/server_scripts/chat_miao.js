// ============================================================================
// 脚本：chat_miao.js（喵化聊天）
// ============================================================================
// 功能：
//   1. 玩家公屏发言结尾没有"喵"就自动补一个"喵"
//   2. 结尾已经有"喵"就不动
//   3. 自动补的"喵"搜不到：源码、服务器日志、网络包、聊天记录导出，
//      都不出现"喵"的字面量（代码里用码点 0x55B5 和翻译键代替，见下文）
//
// 位置：<游戏实例>/kubejs/server_scripts/chat_miao.js
// 生效：/reload（服务器脚本热重载）
// 原理详解：docs/09-隐藏字符实现原理与限制.md
//
// 约定：注释里可以写"喵"（给人看的说明），可执行代码里不能出现"喵"字面量。
// ============================================================================

// ----------------------------------------------------------------------------
// "喵"的 Unicode 码点是 0x55B5。代码里只写这个数字，不写字符本身。
//
// 学习点（JS 字符串本质是 Unicode 码点的序列）：
//   String.fromCharCode(0x55B5) → 反向操作：由码点数字造出字符（本脚本用不到）
//   text.charCodeAt(i)          → 取第 i 个字符的码点（UTF-16 码元）
//   text.codePointAt(i)         → 取第 i 个字符的码点（能正确处理 emoji 等
//                                 码点 > 0xFFFF 的增补平面字符，优先用这个）
// ----------------------------------------------------------------------------
const MIAO_CODE = 0x55B5

// ----------------------------------------------------------------------------
// 订阅"玩家公屏聊天"事件。
//
// PlayerEvents —— KubeJS 内置事件组（源码：plugin/builtin/event/PlayerEvents.java）
// .chat       —— 包装 NeoForge 的 ServerChatEvent，只在玩家真正发聊天时触发
//                （执行命令、私聊不会触发）。
//
// event 对象（源码：player/PlayerChatReceivedKubeEvent.java）：
//   event.message   → String，玩家输入的原始文本
//   event.component → 聊天组件（MutableComponent），真正广播出去的内容
//   event.player    → 发言的 ServerPlayer
//   event.username  → 玩家名
//   event.setComponent(c) → 替换广播内容
//
// 回调不返回值 = 不取消事件，聊天照常广播，我们只是顺手改内容。
// 为什么放 server_scripts：chat 是 GROUP.server(...) 声明的事件，
// 只在 server 脚本可订阅，且修改的是面向全体玩家的数据（权威端逻辑）。见 docs/08。
// ----------------------------------------------------------------------------
PlayerEvents.chat(event => {

	// 去掉结尾空白，防止"你好 "(带空格)被误判为"结尾不是喵"。
	const text = event.message.trimEnd()

	// 空消息防御：防止某些模组发出空消息时追加出一条孤零零的"喵"。
	// 注意 JS 字符串判空用 .length === 0（isEmpty() 是 Java 的方法）。
	if (text.length === 0) {
		return
	}

	// ----------------------------------------------------------------------------
	// 规则判断：结尾已经是"喵"就不处理，保持玩家原话。
	//
	// 关键技巧：比较码点数字，而不是比较字符——
	//   text.codePointAt(text.length - 1) → 结尾字符的码点（数字）
	//   与 MIAO_CODE 全等比较，代码里从头到尾没出现"喵"字面量。
	//
	// （想改成"消息里只要出现过喵就不加"：
	//   for 循环遍历每个字符的 codePointAt 与 MIAO_CODE 比对即可。）
	// ----------------------------------------------------------------------------
	const lastCode = text.codePointAt(text.length - 1)
	if (lastCode === MIAO_CODE) {
		return
	}

	// ----------------------------------------------------------------------------
	// 核心步骤：给聊天组件追加"隐藏的喵"。
	//
	// ① event.component 是当前聊天内容的组件对象。
	//    MC 的显示文字由"文本组件（Component）"描述，树形结构，
	//    可以不断 .append(...) 往末尾追加新片段。
	//
	// ② Text.translate('chat.kubejs.miao') 创建"翻译组件"：
	//    它携带的不是文字，而是一个键名（key）。客户端渲染聊天时，
	//    拿这个键去查自己加载的语言文件（assets/kubejs/lang/*.json），
	//    把键翻译成"喵"再显示。
	//    （原版物品名就是这个机制：日志里只有 item.minecraft.stone，屏幕上显示"石头"）
	//
	//    ★ 这就是"隐藏"的关键 ★
	//    网络上传输的只有键名字符串 "chat.kubejs.miao"，
	//    "喵"字从头到尾不进入网络包、服务器日志、聊天记录文件。
	//    "喵"字只存在于两个地方：
	//      a) 语言文件里（而且是 \u55B5 转义形式，解析后才是喵）
	//      b) 客户端渲染完成后的屏幕像素上
	//
	// ③ event.setComponent(comp) 把改好的组件设回事件。
	//    NeoForge 在事件结束后会用这个组件广播给所有在线玩家。
	// ----------------------------------------------------------------------------
	const comp = event.component
	comp.append(Text.translate('chat.kubejs.miao'))
	event.setComponent(comp)
})

// ============================================================================
// 配套文件（缺一不可）：
//
//   script/assets/kubejs/lang/zh_cn.json
//   script/assets/kubejs/lang/en_us.json
//
//   值写的都是 JSON unicode 转义 "\u55B5"——JSON 解析后才变成"喵"，
//   所以语言文件原文里同样搜不到"喵"字面量（和本脚本的码点方案同理）。
//
//   en_us.json 必须存在：原版语言系统有回退机制——当前语言缺键时
//   回退到 en_us，有它才能保证任何客户端语言的玩家正常显示"喵"。
//
//   语言文件放在 kubejs/assets/ 下，KubeJS 把该目录整个当作
//   客户端资源包挂载（源码：client/KubeJSResourcePackFinder.java）。
//   改动语言文件后按 F3+T 刷新客户端资源。
//
// 已知的诚实限制（详见 docs/09）：
//   - 文字一旦渲染到屏幕上，客户端内存里就是"喵"字，
//     游戏内聊天搜索模组 / OCR 仍能识别——要显示就无法藏。
//   - 玩家自己打的"喵"（上面规则判断放行的情况）是真字符，会正常传输。
// ============================================================================
