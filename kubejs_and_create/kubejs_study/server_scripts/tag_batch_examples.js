// ============================================================================
// 脚本：tag_batch_examples.js（标签批量操作 + 标签配方示例）
// ============================================================================
// 两大部分：
//   A. 配方里用标签做"批量"——一条配方覆盖一整个标签的物品
//   B. 标签事件里批量增删标签——单个/多个/套标签/正则/循环
//
// 位置：<游戏实例>/kubejs/server_scripts/tag_batch_examples.js
// 生效：/reload
//
// 核心认知：标签（Tag）是 MC 的"物品分组"机制（#开头引用）。
// 把标签当配方输入 = 批量；往标签里塞物品 = 批量打标。
// 相关源码：
//   标签事件：server/tag/TagKubeEvent.java、TagWrapper.java
//   过滤器：  server/tag/TagEventFilter.java（支持字符串/标签/正则）
// 基础语法回顾见 docs/07 第 5 节。
// ============================================================================


// ############################################################################
// # B 部分先讲标签事件（注意顺序！）
// ############################################################################
//
// ★ 重要：tags 事件比 recipes 事件先执行！
//   所以可以先在这里建好新标签，下面的配方立刻就能引用它。
//   这个"先建组、后引用"就是标签批量的标准工作流。
//
// 事件目标参数（第一个参数）= 注册表类型，决定改哪类标签：
//   'item' 物品 / 'block' 方块 / 'fluid' 流体 / 'entity_type' 实体 ...
//   同一个 ID 可以在不同注册表里各有各的标签（#minecraft:xxx 物品标签
//   和方块标签是两套体系，改哪个要指明）。
// ############################################################################

ServerEvents.tags('item', event => {

	// ==========================================================================
	// B1. 单个添加
	// ==========================================================================
	// e.add(标签ID, 物品1, 物品2, ...) —— 变长参数，一次塞多个也行。
	// 标签不存在会自动创建，不用先声明。
	// ==========================================================================
	event.add('kubejs_examples:fun_metal',
		'minecraft:iron_nugget',
		'minecraft:gold_nugget',
		'minecraft:copper_ingot'
	)

	// ==========================================================================
	// B2. 批量方式一：标签套标签（最常用！）
	// ==========================================================================
	// add 的"物品"位置放 '#另一个标签' —— 整个标签的所有成员一次性进来。
	// 原版/通用标签成员变了，你的标签自动跟着变，这就是"批量"的精髓：
	// 引用分组而不是枚举成员。
	// ==========================================================================
	event.add('kubejs_examples:sellable', '#minecraft:planks') // 所有木板都可"出售"
	event.add('kubejs_examples:sellable', '#minecraft:coals')  // 所有煤也可"出售"

	// ==========================================================================
	// B3. 批量方式二：正则表达式（按 ID 模式匹配，威力大但要小心）
	// ==========================================================================
	// 源码 TagEventFilter.RegEx：JS 的正则会被包装成正则过滤器，
	// 对每个候选 ID 的完整字符串（如 "minecraft:deepslate_iron_ore"）做匹配。
	//
	// 下例：把所有 ID 形如 xxx_ore 的原版矿石塞进同一个标签。
	// $ 表示"结尾"，避免误伤 deepslate_iron_ore 之外的东西。
	// ==========================================================================
	event.add('kubejs_examples:all_ores', /minecraft:.*_ore$/)

	// ==========================================================================
	// B4. 批量方式三：JS 循环（最灵活，能加逻辑判断）
	// ==========================================================================
	// 前两种覆盖不了的场合用循环：数组来源随便你（写死、拼字符串、
	// 甚至读配置）。循环体内想加几个标签、加什么，完全由你控制。
	// ==========================================================================
	const woods = ['oak', 'spruce', 'birch', 'jungle', 'acacia', 'dark_oak', 'mangrove', 'cherry']
	for (const wood of woods) {
		// 模板字符串 `minecraft:${wood}_log` 逐个拼出 8 种原木的 ID
		event.add('kubejs_examples:logs_for_fun', `minecraft:${wood}_log`)
	}

	// ==========================================================================
	// B5. 批量删除 / 清空 / 整组替换
	// ==========================================================================
	// e.remove(标签, 物品或#标签或正则) —— 从标签里摘掉成员，同样支持批量。
	// ★ 版本注意：TagWrapper 的 removeAll() 已改名 replace()（源码里有
	//   警告日志），但事件级 e.removeAll(标签) 仍然存在，注意区分。
	// ==========================================================================
	event.remove('kubejs_examples:sellable', 'minecraft:crimson_planks') // 摘掉一个
	event.remove('kubejs_examples:all_ores', /minecraft:.*deepslate.*$/) // 正则摘掉一组

	// event.removeAll('kubejs_examples:all_ores') // 整个标签清空（标签本身还在）
	// event.get('kubejs_examples:all_ores').replace() // 等价的新写法（TagWrapper.replace）
})

// 方块标签同理：比如让海绵也能被斧头快速挖掉（mineable/axe 是原版方块标签）
ServerEvents.tags('block', event => {
	event.add('minecraft:mineable/axe', 'minecraft:sponge')
})


// ############################################################################
// # A 部分：配方里用标签 = 批量
// ############################################################################
//
// 三种批量姿势：
//   1. 标签当配方输入 —— 一条配方接收整个标签（最核心！）
//   2. 删改配方时用标签过滤 —— 一次命中一批配方
//   3. JS 循环生成 —— 每个成员一条配方（真需要"逐个"时才用）
// ############################################################################

ServerEvents.recipes(event => {

	// ==========================================================================
	// A1. 标签当输入：一条配方 = 一整个标签
	// ==========================================================================
	// 输入写 '#标签'，任何属于该标签的物品都能参与合成。
	// 玩家放橡木木板或樱花木板，效果一样——不用给每种木板写一条配方。
	// 对比：如果手动枚举，8 种木板 × N 条配方，而且新模组木板覆盖不到。
	// ==========================================================================

	// 任意木板 x1 + 任意煤 x1 → 4 个火把（无序，背包里就能搓）
	event.shapeless('4x minecraft:torch', [
		'#minecraft:planks',
		'#minecraft:coals'
	]).id('kubejs_examples:shapeless/torch_from_any_planks')

	// 上一个事件里建的标签在这里直接用（tags 先于 recipes 执行）
	event.smelting('minecraft:iron_ingot', '#kubejs_examples:fun_metal', 0.5, 100)
		.id('kubejs_examples:smelting/fun_metal_to_iron')

	// ==========================================================================
	// A2. 标签当过滤器：批量删改一批配方
	// ==========================================================================
	// remove/replaceInput/replaceOutput/findRecipes 的过滤器里，
	// input/output 都可以写 '#标签' —— 一次命中所有涉及的配方。
	//
	// 演示用 countRecipes（只查询不改动，跑完看日志数字就知道命中多少）：
	// 日志在 logs/kubejs/server.log，或游戏内 /kubejs info。
	// ==========================================================================
	console.info('木板作为输入的配方数量：', event.countRecipes({ input: '#minecraft:planks' }))
	console.info('产出木板类物品的配方数量：', event.countRecipes({ output: '#minecraft:planks' }))

	// 真正批量删（确认命中数没问题再放开注释）：
	// event.remove({ input: '#minecraft:planks', mod: 'minecraft' }) // 删掉原版所有"木板进、料"的配方

	// 批量替换：全游戏范围内，所有"用任意煤"的配方改成"只用木炭"。
	// 第一参 {} = 不过滤（全部配方）；第二参匹配谁；第三参换成什么。
	event.replaceInput({}, '#minecraft:coals', 'minecraft:charcoal')
		// 注意：replace 系列依赖 schema 的组件匹配，对原版配方效果最好，
		// 对没注册 schema 的模组配方可能不生效（见 docs/06 的结论）

	// ==========================================================================
	// A3. JS 循环批量生成：每个成员一条配方
	// ==========================================================================
	// 标签输入解决 90% 的批量需求（一条配方吃下整组）；
// 真需要"每个物品单独一条配方"（比如各带不同输出）时才上循环。
	//
	// 下例：8 种原木，每种生成一条切石机配方——1 原木直接切 4 个对应木按钮。
	// 注意模板字符串里的 `4x ` 前缀和 A1 里一样是"数量"写法。
	// ==========================================================================
	const woods = ['oak', 'spruce', 'birch', 'jungle', 'acacia', 'dark_oak', 'mangrove', 'cherry']
	for (const wood of woods) {
		event.stonecutting(`4x minecraft:${wood}_button`, `minecraft:${wood}_log`)
			.id(`kubejs_examples:stonecutting/${wood}_log_to_button`)
	}

	// 循环 + 标签输入还能组合出更高级的玩法：
	// "先收集一个数组的输出物，再循环为每个输出建一条 '整个标签 → 该输出' 的配方"，
	// 这样新增成员不用改配方，改数组就行。
})

// ============================================================================
// 学习笔记：
//
// 1. 命名空间约定：
//    '#minecraft:' 原版标签；'#c:' 通用社区标签（Common Tags，模组间互通）；
//    '#kubejs_examples:' 本脚本自建。给整合包打标时优先挂到 c: 系列或自建标签，
//    少直接改 minecraft: 原版标签（改动越小越稳）。
//
// 2. 事件执行顺序：tags → recipes。配方里引用的标签必须在配方应用前就绪，
//    所以"建标签"和"用标签"分属两个事件是刻意设计，不是麻烦。
//
// 3. 正则打标的坑：正则匹配的是 ID 全字符串，'/minecraft:.*_ore$/' 也会命中
//    deepslate_iron_ore、nether_gold_ore 等变体——先想清楚边界（用 $ 和
//    精确前缀），再放大招。写错了不报错，只是多打/漏打，要靠游戏内验证。
//
// 4. 怎么查一个标签里现在有什么？
//    - 游戏内：/kubejs hand 或 JEI 里按 U 查用途、R 查来源
//    - 数据：run 数据包命令 /data? 标签不是实体数据——用
//      /kubejs tags 命令（如果装了）或直接看 mods 内置 tags json
// ============================================================================
