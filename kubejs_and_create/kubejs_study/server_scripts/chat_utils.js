// ============================================================================
// 脚本：chat_utils.js（喵化聊天 · 极简版）
// ============================================================================
// 功能：与 chat_miao.js 相同——公屏发言结尾没有"喵"就补一个，有就不动。
//
// 与 chat_miao.js 的区别（这是本文件存在的意义）：
//   chat_miao.js = 学习版：翻译键 + 语言文件，连"网络包/日志"层都搜不到"喵"
//   chat_utils.js = 极简版：直接追加真字符"喵"，只保证**源码文件**里
//                  搜不到"喵"字面量（恶作剧场景够用，5 行搞定）
//
// ★ 与 chat_miao.js 二选一部署！两个同时装会重复追加（显示"喵喵"）。
//   判断方法：极简版追加的是真字符，chat_miao 的 endsWith('喵') 检查
//   只看原始文本，感知不到翻译键组件，于是两个都追加。
//
// 方案选择依据：需求只到"防搜源码"这层，就不需要翻译键全家桶。
// 对抗层级分析见 docs/09-隐藏字符实现原理与限制.md。
// ============================================================================

// ----------------------------------------------------------------------------
// 订阅"玩家公屏聊天"事件（与 chat_miao.js 同一个事件）。
//
// PlayerEvents.chat 包装 NeoForge 的 ServerChatEvent，只在玩家发聊天时触发。
// event 对象可用属性：
//   event.message   → String，玩家输入的原始文本
//   event.component → 聊天组件（MutableComponent），真正广播的内容
//   event.setComponent(c) → 替换广播内容
// ----------------------------------------------------------------------------
PlayerEvents.chat(event => {

	// trimEnd() 去掉结尾空白，防止"你好 "(带空格)被误判为"结尾不是喵"。
	const text = event.message.trimEnd()

	// 空消息防御：避免给空消息追加出一条孤零零的"喵"。
	if (text.length === 0) {
		return
	}

	// ----------------------------------------------------------------------------
	// 规则判断：结尾已经有"喵"就不动（玩家自己打的不重复加）。
	//
	// ★ 本文件的核心技巧：'\u55B5' 是 JS 字符串转义写法——
	//   源码文件里它只是 6 个 ASCII 字符（反斜杠 u 5 5 B 5），
	//   文本搜索"喵"永远搜不到它；
	//   而 JS 引擎加载这行代码时，它已经解码成"喵"，运行时完全等价于写 '喵'。
	//
	//   等价写法（了解即可）：
	//     String.fromCharCode(0x55B5) —— 用码点数字造字符，同样无字面量
	//     text.codePointAt(...) === 0x55B5 —— 比码点不比字符（chat_miao.js 的做法）
	// ----------------------------------------------------------------------------
	if (!text.endsWith('\u55B5')) {
		// ----------------------------------------------------------------------------
		// 追加后缀：注意这里 append 的是真字符"喵"（转义解码后的结果），
		// 不是翻译键——所以网络包和服务器日志里会出现"喵"。
		// 这就是极简版与 chat_miao.js 的分界线：
		//   防"翻文件搜源码"的人 → 本文件够了
		//   防"搜日志/抓包/聊天记录"的人 → 必须用 chat_miao.js 的翻译键方案
		//
		// setComponent 把改好的组件设回事件，NeoForge 事件结束后广播给全体玩家。
		// ----------------------------------------------------------------------------
		event.setComponent(event.component.append('\u55B5'))
	}
})

